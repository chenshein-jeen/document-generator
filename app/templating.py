def _get_all_sdt_elements(doc: Document) -> list:
    """
    Extract all SDT elements across:

    - document body
    - headers
    - footers
    - first-page headers/footers
    - even-page headers/footers
    """

    elements = list(
        doc.element.xpath(
            '//*[local-name()="sdt"]'
        )
    )

    for section in doc.sections:

        for container in (
            section.header,
            section.footer,
            section.first_page_header,
            section.first_page_footer,
            section.even_page_header,
            section.even_page_footer,
        ):

            if container:

                elements.extend(
                    container._element.xpath(
                        '//*[local-name()="sdt"]'
                    )
                )

    return elements


def _get_sdt_tag_and_alias(sdt):
    """
    Return:

        (tag, alias)
    """

    tag_nodes = sdt.xpath(
        './/*[local-name()="tag"]/@*[local-name()="val"]'
    )

    alias_nodes = sdt.xpath(
        './/*[local-name()="alias"]/@*[local-name()="val"]'
    )

    tag = (
        tag_nodes[0]
        if tag_nodes
        else None
    )

    alias = (
        alias_nodes[0]
        if alias_nodes
        else None
    )

    return tag, alias


def _find_context_key(
    tag: str | None,
    alias: str | None,
    context: dict,
) -> str | None:

    if tag:

        for key in context:

            if key.lower() == tag.lower():

                return key

    if alias:

        for key in context:

            if key.lower() == alias.lower():

                return key

    return None


def extract_content_controls(
    docx_bytes: bytes,
) -> list[str]:
    """
    Extract all dynamic Word Content Controls.

    Includes:
        - SDT Tags
        - SDT Aliases
        - body
        - headers
        - footers
    """

    doc = Document(
        io.BytesIO(docx_bytes)
    )

    sdt_elements = _get_all_sdt_elements(doc)

    tags = set()

    for sdt in sdt_elements:

        tag, alias = _get_sdt_tag_and_alias(sdt)

        if tag == "Title" or alias == "Title":
            continue

        if tag:
            tags.add(tag)

        elif alias:
            tags.add(alias)

    return list(tags)



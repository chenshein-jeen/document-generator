def _parse_field_style_overrides(raw: dict) -> dict:
    """Convert a JSON-friendly field_style_overrides dict (alignment as a
    plain string) into the shape the styling helpers expect (alignment
    as a WD_ALIGN_PARAGRAPH member)."""

    parsed = {}

    for field_name, style in raw.items():
        entry = dict(style)
        alignment = entry.get("alignment")
        if isinstance(alignment, str):
            entry["alignment"] = _PARAGRAPH_ALIGN_NAME_MAP.get(
                alignment.lower(), WD_ALIGN_PARAGRAPH.CENTER
            )
        parsed[field_name] = entry

    return parsed


class StyleConfig:
    """Resolved styling for one render_docx() call. Build via
    _build_style_config() - never instantiate with raw JSON values
    directly, since level_indent/number_hanging need conversion to
    docx.shared.Cm and field_style_overrides needs alignment-string
    conversion."""

    def __init__(
        self,
        *,
        font_name: str = _DEFAULT_FONT_NAME,
        body_size_pt: float = _DEFAULT_BODY_SIZE_PT,
        field_style_overrides: dict | None = None,
        level_num_fmt: dict | None = None,
        level_num_text: dict | None = None,
        level_indent_cm: dict | None = None,
        number_hanging_cm: float = _DEFAULT_NUMBER_HANGING_CM,
    ):
        self.font_name = font_name
        self.body_size_pt = body_size_pt

        self.field_style_overrides = (
            field_style_overrides
            if field_style_overrides is not None
            else dict(_DEFAULT_FIELD_STYLE_OVERRIDES)
        )

        self.level_num_fmt = (
            level_num_fmt
            if level_num_fmt is not None
            else dict(_DEFAULT_LEVEL_NUM_FMT)
        )

        self.level_num_text = (
            level_num_text
            if level_num_text is not None
            else dict(_DEFAULT_LEVEL_NUM_TEXT)
        )

        indent_cm = (
            level_indent_cm
            if level_indent_cm is not None
            else _DEFAULT_LEVEL_INDENT_CM
        )
        self.level_indent = {
            level: Cm(cm) for level, cm in indent_cm.items()
        }

        self.number_hanging = Cm(number_hanging_cm)

    @property
    def table_cell_size_pt(self) -> float:
        return self.body_size_pt



DISTRIBUTION_HEADING_TEXT = "רשימת תפוצה"

# Context key render_docx looks for to append the distribution overflow
# table at the very end of the document (see append_distribution_table_at_document_end).
# Not a real template field - popped out of the context before Jinja/SDT
# processing sees it.
DISTRIBUTION_OVERFLOW_CONTEXT_KEY = "_distribution_overflow_names"


def append_distribution_table_at_document_end(
    doc: Document,
    names: list[str],
) -> None:
    """
    Appends a page break, the "רשימת תפוצה" heading, and the two-column
    distribution table at the very end of the document body - after
    EVERYTHING else, including the closing/signature block - on its own
    page. Used (instead of folding these into Content) when the list is
    too long to fit in the Distribution field itself.

    The table is bidi (RTL), so the first cell in each row (col 0) is
    the visually-RIGHT column and the second (col 1) is the visually-
    LEFT one - left blank and holding the name respectively, per spec.
    equal_columns keeps the divider between them exactly centered
    instead of Word auto-shrinking the blank column.
    """

    if not names:
        return

    body = doc.element.body
    sect_pr = body.find(qn("w:sectPr"))

    def _append(element) -> None:
        # w:sectPr, if present, must stay the last child of w:body - new
        # content goes immediately before it, not after.
        if sect_pr is not None:
            sect_pr.addprevious(element)
        else:
            body.append(element)

    break_p_el = OxmlElement("w:p")
    _append(break_p_el)
    break_paragraph = Paragraph(break_p_el, doc)
    break_run = break_paragraph.add_run()
    break_run.add_break(WD_BREAK.PAGE)

    heading_p_el = OxmlElement("w:p")
    _append(heading_p_el)
    heading_paragraph = Paragraph(heading_p_el, doc)
    _add_direction_aware_runs(
        heading_paragraph,
        DISTRIBUTION_HEADING_TEXT,
    )
    _style_paragraph(
        heading_paragraph,
        size_pt=14,
        bold=True,
        underline=True,
        alignment=WD_ALIGN_PARAGRAPH.CENTER,
        rtl_paragraph=True,
    )

    rows = [["", name] for name in names]
    tbl = _build_table_element(
        rows,
        align="center",
        header_row=False,
        bold_cells=True,
        equal_columns=True,
    )
    _append(tbl)



# MAIN DOCX RENDERING
# ============================================================

def render_docx(
    docx_bytes: bytes,
    context: dict,
    *,
    style_overrides: dict | None = None,
    field_map_overrides: dict | None = None,
) -> bytes:
    """
    Render the DOCX template.

    style_overrides is a template's own parsed "<name>.style.json", if
    it has one (see app.main) - font/size/field styling/numbering
    format that differs from the defaults. Falls back to today's
    hardcoded defaults for anything not specified, or entirely when
    None/empty (e.g. dani/hadas today).

    field_map_overrides is a template's own parsed "<name>.fields.json",
    if it has one - which placeholder name plays the Content/Number/
    Subject/Distribution/date-field roles for THIS template, when it
    doesn't use today's literal names. Same fallback behavior as
    style_overrides.
    """

    style_token = _style_context.set(
        _build_style_config(style_overrides)
    )
    field_map_token = _field_map_context.set(
        _build_field_map(field_map_overrides)
    )

    try:
        return _render_docx_impl(docx_bytes, context)
    finally:
        _style_context.reset(style_token)
        _field_map_context.reset(field_map_token)


def _render_docx_impl(
    docx_bytes: bytes,
    context: dict,
) -> bytes:
    """
    Render the DOCX template.

    Supports:

        - Jinja placeholders
        - Native Word SDT fields
        - Structured Content SDT
        - Native multilevel numbering
        - RTL Hebrew
        - Dynamic dates
        - Static field formatting
    """

    render_context = dict(
        context
    )

    fold_distribution_fields(
        render_context,
        _current_field_map().distribution_field,
    )

    # --------------------------------------------------------
    # Dates — caller wins; today only as fallback
    #
    # If the request already set Date_Army / Date_ArmyHebrew (or
    # whatever names this template's field map uses), keep them.
    # Otherwise fill today's Gregorian / Hebrew pair. No fields.json
    # "disable" hack needed to pass a custom date from Langflow.
    # --------------------------------------------------------

    current_dates = _get_current_dates()
    field_map = _current_field_map()

    def _has_nonempty(field_name: str) -> bool:
        for key, value in render_context.items():
            if key.lower() != field_name.lower():
                continue
            if value is None:
                return False
            if isinstance(value, str) and not value.strip():
                return False
            return True
        return False

    if not _has_nonempty(field_map.date_army_field):
        render_context[field_map.date_army_field] = current_dates["Date_Army"]
    if not _has_nonempty(field_map.date_army_hebrew_field):
        render_context[field_map.date_army_hebrew_field] = current_dates[
            "Date_ArmyHebrew"
        ]

    # --------------------------------------------------------
    # Structured content
    #
    # If content is a list, Jinja cannot directly render it.
    # Replace it with a marker and handle it after rendering.
    # --------------------------------------------------------

    content_key = None

    for key in render_context:

        if (
            key.lower()
            == _current_field_map().content_field.lower()
        ):

            content_key = key
            break

    content_items = (
        render_context.get(
            content_key
        )
        if content_key
        else None
    )

    has_structured_content = isinstance(
        content_items,
        list,
    )

    # Jinja can't render a list directly, so it gets a marker string
    # substituted in for the {{ Content }} case. This must NOT leak into
    # render_context itself: the native-SDT fill below (_fill_content_controls)
    # needs the real list, not the marker string, or it silently no-ops on
    # the Content control instead of inserting the numbered paragraphs.
    jinja_context = dict(
        render_context
    )

    if has_structured_content:

        jinja_context[
            content_key
        ] = CONTENT_MARKER

    distribution_field = _current_field_map().distribution_field
    distribution_key = next(
        (
            key
            for key in render_context
            if key.lower() == distribution_field.lower()
        ),
        distribution_field,
    )
    distribution_names = normalize_distribution_names(
        render_context.get(distribution_key)
    )
    jinja_context[distribution_key] = DISTRIBUTION_MARKER
    if distribution_key != distribution_field:
        jinja_context[distribution_field] = DISTRIBUTION_MARKER

    # --------------------------------------------------------
    # Render Jinja
    # --------------------------------------------------------

    doc_tpl = DocxTemplate(
        io.BytesIO(docx_bytes)
    )

    doc_tpl.render(
        jinja_context
    )

    out = io.BytesIO()

    doc_tpl.save(
        out
    )

    # --------------------------------------------------------
    # Reload with python-docx
    # --------------------------------------------------------

    doc = Document(
        io.BytesIO(
            out.getvalue()
        )
    )

    # --------------------------------------------------------
    # Static field styling
    # --------------------------------------------------------

    _apply_static_field_styles_post_render(
        doc,
        render_context,
    )

    # --------------------------------------------------------
    # Native Word SDTs
    #
    # IMPORTANT:
    # Content SDT is handled here before Jinja marker handling.
    # --------------------------------------------------------

    filled_distribution_sdt = _fill_content_controls(
        doc,
        render_context,
    )

    # --------------------------------------------------------
    # Jinja structured Content
    #
    # Only if the template uses:
    #
    #     {{ Content }}
    #
    # rather than an SDT.
    # --------------------------------------------------------

    if has_structured_content:

        marker_paragraphs = [
            p
            for p in doc.paragraphs
            if p.text == CONTENT_MARKER
        ]

        for anchor in marker_paragraphs:

            _insert_structured_content_at_marker(
                doc,
                anchor,
                content_items,
            )

    distribution_placed = False

    distribution_marker_paragraphs = [
        p
        for p in doc.paragraphs
        if p.text == DISTRIBUTION_MARKER
    ]

    for anchor in distribution_marker_paragraphs:

        _insert_distribution_list_at_marker(
            doc,
            anchor,
            distribution_names,
        )
        distribution_placed = True

    if _nemen_placeholder_paragraphs(doc):

        _replace_nemen_placeholders_with_distribution(
            doc,
            distribution_names,
        )
        distribution_placed = True

    if not distribution_placed and not filled_distribution_sdt:

        _insert_distribution_list_after_heading(
            doc,
            distribution_names,
        )

    # --------------------------------------------------------
    # Clean excessive blank paragraphs.
    # --------------------------------------------------------

    _collapse_blank_paragraphs(
        doc,
        max_consecutive=2,
    )

    # --------------------------------------------------------
    # Line spacing: 1.5 everywhere. Paragraph spacing (space
    # before/after) is untouched - the blank separator paragraphs
    # inserted before each level-1 section remain the only source of
    # extra space between paragraphs.
    # --------------------------------------------------------

    _apply_line_spacing_everywhere(
        doc,
        line_spacing=1.5,
    )

    _ensure_continuation_header_gap(doc)

    # --------------------------------------------------------
    # Save
    # --------------------------------------------------------

    final = io.BytesIO()

    doc.save(
        final
    )

    return final.getvalue()
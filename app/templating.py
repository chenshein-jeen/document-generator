def _style_run(
    run,
    *,
    size_pt: float | None = None,
    bold: bool = False,
    italic: bool = False,
    underline: bool = False,
    rtl: bool | None = True,
) -> None:

    style = _current_style()

    if size_pt is None:
        size_pt = style.body_size_pt

    font_name = style.font_name

    # --------------------------------------------------------
    # python-docx formatting
    # --------------------------------------------------------

    run.font.name = font_name
    run.font.size = Pt(size_pt)
    run.font.bold = bold
    run.font.italic = italic
    run.font.underline = underline

    run.font.color.rgb = RGBColor(
        0,
        0,
        0,
    )

    r_pr = run._r.get_or_add_rPr()

    # --------------------------------------------------------
    # Font
    # --------------------------------------------------------

    r_fonts = r_pr.find(
        qn("w:rFonts")
    )

    if r_fonts is None:

        r_fonts = OxmlElement(
            "w:rFonts"
        )

        r_pr.insert(
            0,
            r_fonts
        )

    r_fonts.set(
        qn("w:ascii"),
        font_name,
    )

    r_fonts.set(
        qn("w:hAnsi"),
        font_name,
    )

    r_fonts.set(
        qn("w:cs"),
        font_name,
    )

    r_fonts.set(
        qn("w:eastAsia"),
        font_name,
    )

    # --------------------------------------------------------
    # Font size
    # --------------------------------------------------------

    half_points = str(
        int(
            round(
                size_pt * 2
            )
        )
    )

    for tag in (
        "w:sz",
        "w:szCs",
    ):

        el = r_pr.find(
            qn(tag)
        )

        if el is None:

            el = OxmlElement(
                tag
            )

            r_pr.append(
                el
            )

        el.set(
            qn("w:val"),
            half_points,
        )

    # --------------------------------------------------------
    # Bold
    # --------------------------------------------------------

    for tag in (
        "w:b",
        "w:bCs",
    ):

        existing = r_pr.find(
            qn(tag)
        )

        if existing is not None:

            r_pr.remove(
                existing
            )

        if bold:

            r_pr.append(
                OxmlElement(tag)
            )

    # --------------------------------------------------------
    # Italic
    # --------------------------------------------------------

    for tag in (
        "w:i",
        "w:iCs",
    ):

        existing = r_pr.find(
            qn(tag)
        )

        if existing is not None:

            r_pr.remove(
                existing
            )

        if italic:

            r_pr.append(
                OxmlElement(tag)
            )

    # --------------------------------------------------------
    # Underline
    # --------------------------------------------------------

    underline_el = r_pr.find(
        qn("w:u")
    )

    if underline_el is not None:

        r_pr.remove(
            underline_el
        )

    if underline:

        underline_el = OxmlElement(
            "w:u"
        )

        underline_el.set(
            qn("w:val"),
            "single",
        )

        r_pr.append(
            underline_el
        )

    # --------------------------------------------------------
    # Black
    # --------------------------------------------------------

    color_el = r_pr.find(
        qn("w:color")
    )

    if color_el is None:

        color_el = OxmlElement(
            "w:color"
        )

        r_pr.append(
            color_el
        )

    color_el.set(
        qn("w:val"),
        "000000",
    )

    # --------------------------------------------------------
    # RTL
    # --------------------------------------------------------

    if rtl is not None:

        rtl_el = r_pr.find(
            qn("w:rtl")
        )

        if rtl:

            if rtl_el is None:

                rtl_el = OxmlElement(
                    "w:rtl"
                )

                r_pr.append(
                    rtl_el
                )

            rtl_el.set(
                qn("w:val"),
                "1",
            )

        elif rtl_el is not None:

            r_pr.remove(
                rtl_el
            )


# ============================================================
# HYPHEN SPACING
# ============================================================

# A hyphen tightly joining two words/tokens (no space, or a space on only
# one side - e.g. "בסך-הכל" or "בסך- הכל") gets exactly one space on each
# side: "בסך - הכל". Already-correct spacing is left as-is (idempotent),
# and "--" / a hyphen at the very start or end of the text is left alone.
_HYPHEN_RE = re.compile(r"(?<=\S)[ \t]*(?<!-)-(?!-)[ \t]*(?=\S)")


def _normalize_hyphen_spacing(text: str) -> str:
    return _HYPHEN_RE.sub(" - ", text)


# ============================================================
# DIRECTION-AWARE RUNS
# ============================================================

_LATIN_TOKEN_RE = re.compile(
    r"[A-Za-z]+|[^A-Za-z]+"
)


def _add_direction_aware_runs(
    paragraph,
    text: str,
    *,
    size_pt: float | None = None,
    bold: bool = False,
    italic: bool = False,
    underline: bool = False,
) -> None:

    text = _normalize_hyphen_spacing(text)

    for token in _LATIN_TOKEN_RE.findall(
        text
    ):

        is_latin = bool(
            re.fullmatch(
                r"[A-Za-z]+",
                token,
            )
        )

        run = paragraph.add_run(
            token
        )

        _style_run(
            run,
            size_pt=size_pt,
            bold=bold,
            italic=italic,
            underline=underline,
            rtl=not is_latin,
        )


def _alignment_for_item(item: dict, default=WD_ALIGN_PARAGRAPH.JUSTIFY):
    """Map JSON/canvas align onto Word w:jc.

    The {{content}} placeholder is RTL + justify. Canvas Hebrew
    blocks almost always send align="right" (visual start in an
    HTML rtl editor). Word with w:bidi mirrors w:jc, so writing
    jc=right on those paragraphs becomes a left-aligned LTR look
    and overwrites the template. Treat "right" as inherit-default.
    Explicit left / center / justify still apply.
    """

    align = item.get("align")
    if align is None:
        return default
    if isinstance(align, str):
        key = align.lower()
        if key == "right":
            return default
        return _PARAGRAPH_ALIGN_NAME_MAP.get(key, default)
    return align


def _configured_heading_style(tag: str | None) -> dict:
    overrides = _current_style().field_style_overrides
    tag_key = (tag or "h1").lower()
    return (
        overrides.get(tag_key)
        or overrides.get(tag_key.upper())
        or overrides.get("Heading")
        or {
            "size_pt": 14,
            "bold": True,
            "underline": True,
        }
    )


def _is_heading_item(item: dict) -> bool:
    tag = (item.get("tag") or "").lower()
    return tag in {"h1", "h2", "h3", "h4", "h5", "h6"} or item.get("type") == "heading"


def _apply_heading_style(item: dict) -> dict:
    """Headings use the template style (default David 14 bold underline)."""

    if not _is_heading_item(item):
        return item

    style = _configured_heading_style(item.get("tag"))
    if item.get("size_pt") is None and style.get("size_pt") is not None:
        item["size_pt"] = style["size_pt"]
    if item.get("align") is None and style.get("alignment") is not None:
        item["align"] = style["alignment"]

    base_runs = item.get("runs") or [{"text": item.get("text") or ""}]
    styled_runs = []
    for run in base_runs:
        styled = dict(run)
        styled["bold"] = bool(run.get("bold") or style.get("bold"))
        styled["underline"] = bool(run.get("underline") or style.get("underline"))
        styled["italic"] = bool(run.get("italic") or style.get("italic"))
        styled_runs.append(styled)
    item["runs"] = styled_runs
    return item


def _write_item_text(
    paragraph,
    item: dict,
    *,
    size_pt: float | None = None,
    bold: bool = False,
    italic: bool = False,
    underline: bool = False,
) -> bool:
    """Write plain text or structured runs onto a paragraph.

    Returns True when mixed inline marks were applied, so the caller
    must not restyle every run with a single bold/underline flag.
    """

    item = _apply_heading_style(item)
    if item.get("size_pt") is not None and size_pt is None:
        size_pt = item["size_pt"]

    runs = item.get("runs")
    if not runs:
        text = str(item.get("text") or "")
        _add_direction_aware_runs(
            paragraph,
            text,
            size_pt=size_pt,
            bold=bold,
            italic=italic,
            underline=underline,
        )
        return False

    rich = False
    for run in runs:
        piece = str(run.get("text") or "")
        if run.get("break") or piece == "\n":
            if paragraph.runs:
                paragraph.runs[-1].add_break()
            continue
        run_bold = bool(run.get("bold", bold))
        run_underline = bool(run.get("underline", underline))
        run_italic = bool(run.get("italic", italic))
        if run_bold != bold or run_underline != underline or run_italic != italic:
            rich = True
        _add_direction_aware_runs(
            paragraph,
            piece,
            size_pt=run.get("size_pt", size_pt),
            bold=run_bold,
            italic=run_italic,
            underline=run_underline,
        )
    return rich or True


# ============================================================
# PARAGRAPH STYLING
# ============================================================

def _style_paragraph(
    paragraph,
    *,
    size_pt: float | None = None,
    bold: bool = False,
    italic: bool = False,
    underline: bool = False,
    alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
    rtl_paragraph: bool = True,
    space_before=Pt(0),
    space_after=Pt(0),
    touch_runs: bool = True,
) -> None:

    pf = paragraph.paragraph_format

    pf.alignment = alignment

    pf.line_spacing = 1.5

    pf.space_before = space_before

    pf.space_after = space_after

    # IMPORTANT:
    # Do NOT set right/left indentation here for numbered paragraphs.
    #
    # Native Word numbering already owns the indentation.
    #
    # This avoids conflicts between:
    #     w:numPr
    # and:
    #     w:ind

    _set_bidi(
        paragraph,
        rtl=rtl_paragraph,
    )

    if not touch_runs:
        return

    for run in paragraph.runs:

        _style_run(
            run,
            size_pt=size_pt,
            bold=bold,
            italic=italic,
            underline=underline,
            rtl=rtl_paragraph,
        )



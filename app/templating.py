def _int_keyed(raw: dict | None) -> dict | None:
    """Level-keyed overrides (level_num_fmt, level_num_text,
    level_indent_cm) are looked up elsewhere with int keys (e.g.
    style.level_indent[1]), but a JSON-parsed override has string keys
    ("1", "2", "3") - normalize them here, once, rather than at every
    lookup site."""

    if not raw:
        return None

    return {int(level): value for level, value in raw.items()}


def _build_style_config(overrides: dict | None) -> StyleConfig:
    """Build a StyleConfig from a template's parsed "<name>.style.json",
    if it has one - falling back to _DEFAULT_STYLE (today's hardcoded
    values) for anything the override doesn't specify, or entirely when
    overrides is empty/None."""

    if not overrides:
        return _DEFAULT_STYLE

    raw_field_overrides = overrides.get("field_style_overrides")
    merged_fields = dict(_DEFAULT_FIELD_STYLE_OVERRIDES)
    if raw_field_overrides:
        merged_fields.update(_parse_field_style_overrides(raw_field_overrides))

    return StyleConfig(
        font_name=overrides.get("font_name", _DEFAULT_FONT_NAME),
        body_size_pt=overrides.get("body_size_pt", _DEFAULT_BODY_SIZE_PT),
        field_style_overrides=merged_fields,
        level_num_fmt=_int_keyed(overrides.get("level_num_fmt")),
        level_num_text=_int_keyed(overrides.get("level_num_text")),
        level_indent_cm=_int_keyed(overrides.get("level_indent_cm")),
        number_hanging_cm=overrides.get(
            "number_hanging_cm", _DEFAULT_NUMBER_HANGING_CM
        ),
    )



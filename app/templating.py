def _get_existing_ids(
    root,
    element_name: str,
    attribute_name: str,
) -> list[int]:

    result = []

    for element in root.findall(
        qn(element_name)
    ):

        value = element.get(
            qn(attribute_name)
        )

        if value is None:
            continue

        try:
            result.append(
                int(value)
            )
        except ValueError:
            pass

    return result


def _next_id(
    root,
    element_name: str,
    attribute_name: str,
    default: int,
) -> int:

    ids = _get_existing_ids(
        root,
        element_name,
        attribute_name,
    )

    return (
        max(ids) + 1
        if ids
        else default
    )


def _do_not_flip_mirror_indents(doc: Document) -> bool:
    """True when the template disables RTL indent mirroring.

    בינה (and other Word-Hebrew templates) set
    compatSetting doNotFlipMirrorIndents=1. Then w:ind w:left stays
    on the physical left, so a list built for 'Word will mirror this'
    renders as LTR. Those templates already store RTL lists as
    w:ind w:right (see abstractNum 1 in the בינה numbering.xml).
    """

    try:
        root = doc.settings.element
    except Exception:
        return False

    for el in root.iter(qn("w:compatSetting")):
        if el.get(qn("w:name")) == "doNotFlipMirrorIndents":
            return el.get(qn("w:val")) in {"1", "true", "on"}
    return False


def _build_numbering_level(
    *,
    ilvl: int,
    num_fmt: str,
    lvl_text: str,
    indent,
    hanging,
    restart_after: int | None = None,
    indent_from: str = "left",
):
    """
    Build one <w:lvl> definition.

    ilvl 0 -> 1.
    ilvl 1 -> א.
    ilvl 2 -> 1)
    """

    lvl = OxmlElement(
        "w:lvl"
    )

    lvl.set(
        qn("w:ilvl"),
        str(ilvl),
    )

    # Start numbering from 1.
    start = OxmlElement(
        "w:start"
    )

    start.set(
        qn("w:val"),
        "1",
    )

    lvl.append(start)

    # Number format.
    num_fmt_el = OxmlElement(
        "w:numFmt"
    )

    num_fmt_el.set(
        qn("w:val"),
        num_fmt,
    )

    lvl.append(num_fmt_el)

    # Restart child levels.
    #
    # Level 2 restarts when level 1 changes.
    # Level 3 restarts when level 2 changes.
    if restart_after is not None:

        restart = OxmlElement(
            "w:lvlRestart"
        )

        restart.set(
            qn("w:val"),
            str(restart_after),
        )

        lvl.append(restart)

    # Actual visible numbering pattern.
    lvl_text_el = OxmlElement(
        "w:lvlText"
    )

    lvl_text_el.set(
        qn("w:val"),
        lvl_text,
    )

    lvl.append(lvl_text_el)

    suff = OxmlElement("w:suff")
    suff.set(qn("w:val"), "space")
    lvl.append(suff)

    # Number alignment.
    #
    # lvlJc stays "left" either way: that is what Word writes for this
    # template's own RTL numbered list (abstractNum 1).
    #
    # Indent side depends on the template. Word's RTL gallery uses
    # w:ind w:left and relies on mirroring. בינה sets
    # doNotFlipMirrorIndents, and stores RTL lists as w:ind w:right
    # with no num-tab. Using w:left there keeps the marker on the
    # physical left (LTR).
    lvl_jc = OxmlElement(
        "w:lvlJc"
    )

    lvl_jc.set(
        qn("w:val"),
        "left",
    )

    lvl.append(lvl_jc)

    # --------------------------------------------------------
    # Paragraph properties
    # --------------------------------------------------------

    p_pr = OxmlElement(
        "w:pPr"
    )

    indent_attr = "w:right" if indent_from == "right" else "w:left"

    if indent_from != "right":
        # Tab stop the number jumps to (w:suff defaults to "tab" when
        # omitted). Physical-left lists only: pos is from the left
        # margin. The template RTL list does not use this tab.
        tabs = OxmlElement(
            "w:tabs"
        )

        tab = OxmlElement(
            "w:tab"
        )

        tab.set(
            qn("w:val"),
            "num",
        )

        tab.set(
            qn("w:pos"),
            str(indent.twips),
        )

        tabs.append(tab)

        p_pr.append(tabs)

    ind = OxmlElement(
        "w:ind"
    )

    ind.set(
        qn(indent_attr),
        str(indent.twips),
    )
    if indent_from == "right":
        ind.set(qn("w:start"), str(indent.twips))

    # Hanging on a physical-right RTL list pulls the number back to
    # the page margin, so every level looks flush. Only LTR lists
    # (mirrored left indent) get hanging.
    if indent_from != "right":
        ind.set(
            qn("w:hanging"),
            str(hanging.twips),
        )

    p_pr.append(ind)

    lvl.append(p_pr)

    # --------------------------------------------------------
    # Number font
    # --------------------------------------------------------

    r_pr = OxmlElement(
        "w:rPr"
    )

    r_fonts = OxmlElement(
        "w:rFonts"
    )

    font_name = _current_style().font_name

    r_fonts.set(
        qn("w:ascii"),
        font_name,
    )

    r_fonts.set(
        qn("w:hAnsi"),
        font_name,
    )

    r_fonts.set(
        qn("w:cs"),
        font_name,
    )

    r_fonts.set(
        qn("w:eastAsia"),
        font_name,
    )

    r_pr.append(r_fonts)

    rtl = OxmlElement(
        "w:rtl"
    )

    rtl.set(
        qn("w:val"),
        "1",
    )

    r_pr.append(rtl)

    lvl.append(r_pr)

    return lvl


def _get_or_create_numbering_part(doc: Document) -> NumberingPart:
    """Return the document numbering part, creating an empty one if missing.

    Do not use ``doc.part.numbering_part``: when ``word/numbering.xml`` is
    absent, python-docx calls ``NumberingPart.new()``, which raises
    ``NotImplementedError``. That breaks templates like bina that have no
    pre-existing numbered lists.
    """

    try:
        return doc.part.part_related_by(RT.NUMBERING)
    except KeyError:
        pass

    part = NumberingPart(
        PackURI("/word/numbering.xml"),
        CT.WML_NUMBERING,
        parse_xml(_EMPTY_NUMBERING_XML),
        doc.part.package,
    )
    doc.part.relate_to(part, RT.NUMBERING)
    return part


def _ensure_multilevel_numbering(
    doc: Document,
) -> int:
    """
    Creates a new native Word multilevel numbering definition.

    Level 1:
        1. 2. 3.

    Level 2:
        א. ב. ג.

    Level 3:
        1) 2) 3)
    """

    numbering_part = _get_or_create_numbering_part(doc)

    root = numbering_part.element
    indent_from = (
        "right" if _do_not_flip_mirror_indents(doc) else "left"
    )

    # --------------------------------------------------------
    # Find free IDs
    # --------------------------------------------------------

    abstract_id = _next_id(
        root,
        "w:abstractNum",
        "w:abstractNumId",
        default=0,
    )

    num_id = _next_id(
        root,
        "w:num",
        "w:numId",
        default=1,
    )

    # --------------------------------------------------------
    # abstractNum
    # --------------------------------------------------------

    abstract_num = OxmlElement(
        "w:abstractNum"
    )

    abstract_num.set(
        qn("w:abstractNumId"),
        str(abstract_id),
    )

    # "multilevel" (not "hybridMultilevel") is required for a child level
    # to automatically restart its counter whenever its parent level
    # increments - confirmed by diffing against the numbering.xml Word
    # itself writes for its built-in "1. א. 1)" gallery style, which is
    # w:multiLevelType="multilevel". hybridMultilevel is a flatter/legacy
    # mode that doesn't reliably honor per-level restarts, even with an
    # explicit w:lvlRestart set.
    multi_level_type = OxmlElement(
        "w:multiLevelType"
    )

    multi_level_type.set(
        qn("w:val"),
        "multilevel",
    )

    abstract_num.append(
        multi_level_type
    )

    style = _current_style()

    # --------------------------------------------------------
    # Level 1
    # --------------------------------------------------------

    abstract_num.append(
        _build_numbering_level(
            ilvl=0,
            num_fmt=style.level_num_fmt[1],
            lvl_text=style.level_num_text[1],
            indent=style.level_indent[1],
            hanging=style.number_hanging,
            indent_from=indent_from,
        )
    )

    # --------------------------------------------------------
    # Level 2
    #
    # hebrew2 = Hebrew alphabet:
    # א, ב, ג, ...
    # --------------------------------------------------------

    abstract_num.append(
        _build_numbering_level(
            ilvl=1,
            num_fmt=style.level_num_fmt[2],
            lvl_text=style.level_num_text[2],
            indent=style.level_indent[2],
            hanging=style.number_hanging,
            restart_after=None,
            indent_from=indent_from,
        )
    )

    # --------------------------------------------------------
    # Level 3
    # --------------------------------------------------------

    abstract_num.append(
        _build_numbering_level(
            ilvl=2,
            num_fmt=style.level_num_fmt[3],
            lvl_text=style.level_num_text[3],
            indent=style.level_indent[3],
            hanging=style.number_hanging,
            restart_after=None,
            indent_from=indent_from,
        )
    )

    # --------------------------------------------------------
    # Insert abstractNum before w:num
    # --------------------------------------------------------

    existing_nums = root.findall(
        qn("w:num")
    )

    if existing_nums:

        existing_nums[0].addprevious(
            abstract_num
        )

    else:

        root.append(
            abstract_num
        )

    # --------------------------------------------------------
    # Create numbering instance
    # --------------------------------------------------------

    num = OxmlElement(
        "w:num"
    )

    num.set(
        qn("w:numId"),
        str(num_id),
    )

    abstract_ref = OxmlElement(
        "w:abstractNumId"
    )

    abstract_ref.set(
        qn("w:val"),
        str(abstract_id),
    )

    num.append(
        abstract_ref
    )

    root.append(
        num
    )

    return num_id


def _set_num_pr(
    paragraph,
    *,
    ilvl: int,
    num_id: int,
) -> None:
    """
    Attach native Word numbering to a paragraph.

    Python level:
        1 -> ilvl 0
        2 -> ilvl 1
        3 -> ilvl 2
    """

    p_pr = paragraph._p.get_or_add_pPr()

    # Remove an existing numPr if one exists.
    existing = p_pr.find(
        qn("w:numPr")
    )

    if existing is not None:
        p_pr.remove(existing)

    num_pr = OxmlElement(
        "w:numPr"
    )

    ilvl_el = OxmlElement(
        "w:ilvl"
    )

    ilvl_el.set(
        qn("w:val"),
        str(ilvl),
    )

    num_pr.append(
        ilvl_el
    )

    num_id_el = OxmlElement(
        "w:numId"
    )

    num_id_el.set(
        qn("w:val"),
        str(num_id),
    )

    num_pr.append(
        num_id_el
    )

    # Numbering should be near the beginning of pPr.
    p_pr.insert(
        0,
        num_pr,
    )


def _apply_numbered_paragraph_indent(paragraph, level: int, doc: Document) -> None:
    """Write w:ind on the paragraph itself.

    RTL + hanging: Word draws the numbered first line on the page
    margin, so 1. and א. look flush. Nested levels use a block
    w:right / w:start shift with no hanging.
    """

    style = _current_style()
    indent = style.level_indent.get(level)
    if indent is None:
        return

    indent_from = "right" if _do_not_flip_mirror_indents(doc) else "left"
    p_pr = paragraph._p.get_or_add_pPr()
    existing = p_pr.find(qn("w:ind"))
    if existing is not None:
        p_pr.remove(existing)

    twips = str(int(indent.twips))
    ind = OxmlElement("w:ind")
    if indent_from == "right":
        ind.set(qn("w:right"), twips)
        # Logical start = right edge in a bidi paragraph (Word 2010+).
        ind.set(qn("w:start"), twips)
    else:
        ind.set(qn("w:left"), twips)
        ind.set(qn("w:hanging"), str(int(style.number_hanging.twips)))
    p_pr.append(ind)



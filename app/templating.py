# JINJA CONTENT MARKER
# ============================================================

def _insert_structured_content_at_marker(
    doc: Document,
    anchor_paragraph,
    items: list[dict],
) -> None:
    """
    Handles structured content coming from a Jinja placeholder:

        {{ content }}

    The marker paragraph is used as an anchor.
    """

    if not items:

        parent = (
            anchor_paragraph._p.getparent()
        )

        if parent is not None:

            parent.remove(
                anchor_paragraph._p
            )

        return

    num_id = _ensure_multilevel_numbering(
        doc
    )

    # See _insert_structured_content_before_sdt: the blank separator
    # must only appear BETWEEN two level-1 sections, not right after a
    # level-0 intro paragraph.
    seen_level_1 = False

    for item in items:

        if not isinstance(
            item,
            dict,
        ):
            continue

        # ----------------------------------------------------
        # Heading item (e.g. distribution-list section title)
        # ----------------------------------------------------

        if item.get("type") == "heading":

            heading_text = str(item.get("text", "")).strip()

            if heading_text:

                for _ in range(2):

                    blank = (
                        anchor_paragraph
                        .insert_paragraph_before()
                    )

                    _style_paragraph(
                        blank,
                        alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
                        rtl_paragraph=True,
                    )

                paragraph = (
                    anchor_paragraph
                    .insert_paragraph_before()
                )

                _write_item_text(
                    paragraph,
                    {"text": heading_text, "runs": item.get("runs")},
                    size_pt=item.get("size_pt", 14),
                    bold=item.get("bold", True),
                    underline=item.get("underline", True),
                )

                _style_paragraph(
                    paragraph,
                    size_pt=item.get("size_pt", 14),
                    bold=item.get("bold", True),
                    underline=item.get("underline", True),
                    alignment=_alignment_for_item(item, WD_ALIGN_PARAGRAPH.JUSTIFY),
                    rtl_paragraph=True,
                    touch_runs=not item.get("runs"),
                )

            continue

        # ----------------------------------------------------
        # Table item (from an uploaded docx/msg file, or an
        # explicitly-built list like the distribution overflow table)
        # ----------------------------------------------------

        if item.get("type") == "table":

            rows = item.get("rows") or []

            if rows:

                _new_table_before_paragraph(
                    anchor_paragraph,
                    rows,
                    align=item.get("align", "center"),
                    header_row=item.get("header_row", True),
                    bold_cells=item.get("bold_cells", False),
                    equal_columns=item.get("equal_columns", False),
                    bidi=item.get("bidi", True),
                )

            continue

        level = item.get(
            "level"
        )

        if level not in (
            0,
            1,
            2,
            3,
        ):
            level = 0

        apply_num = _should_apply_word_numbering(item, level)
        if apply_num:
            item = _strip_duplicate_outline_markers(item)

        text = str(
            item.get(
                "text",
                "",
            )
        ).strip()

        if not text and not item.get("runs"):
            continue

        # ----------------------------------------------------
        # "אחריות" lines - see _insert_structured_content_before_sdt.
        # ----------------------------------------------------

        achrayut_text = _clean_achrayut_text(text)

        if _is_achrayut_clause(achrayut_text):

            achrayut_style = _current_style().field_style_overrides.get(
                "אחריות",
                {},
            )

            blank = (
                anchor_paragraph
                .insert_paragraph_before()
            )

            _style_paragraph(
                blank,
                alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
                rtl_paragraph=True,
            )

            paragraph = (
                anchor_paragraph
                .insert_paragraph_before()
            )

            _add_direction_aware_runs(
                paragraph,
                achrayut_text,
            )

            _style_paragraph(
                paragraph,
                size_pt=achrayut_style.get(
                    "size_pt", _current_style().body_size_pt
                ),
                bold=achrayut_style.get(
                    "bold", True
                ),
                underline=achrayut_style.get(
                    "underline", True
                ),
                # Word mirrors w:jc for RTL/bidi paragraphs (same
                # mirroring already established for w:ind elsewhere in
                # this file) - RIGHT here is what actually displays as
                # left-aligned. Confirmed via Word's own alignment
                # button state, not just rendering appearance.
                alignment=achrayut_style.get(
                    "alignment", WD_ALIGN_PARAGRAPH.RIGHT
                ),
                rtl_paragraph=True,
            )

            continue

        # ----------------------------------------------------
        # Level 0
        # ----------------------------------------------------

        if level == 0:

            paragraph = (
                anchor_paragraph
                .insert_paragraph_before()
            )

            _write_item_text(
                paragraph,
                item,
                size_pt=item.get("size_pt"),
            )

            _style_paragraph(
                paragraph,
                size_pt=item.get("size_pt"),
                alignment=_alignment_for_item(item, WD_ALIGN_PARAGRAPH.JUSTIFY),
                rtl_paragraph=True,
                touch_runs=not item.get("runs"),
            )

            continue

        # ----------------------------------------------------
        # Space between main sections
        # ----------------------------------------------------

        if (
            level == 1
            and
            seen_level_1
        ):

            blank = (
                anchor_paragraph
                .insert_paragraph_before()
            )

            _style_paragraph(
                blank,
                alignment=(
                    WD_ALIGN_PARAGRAPH.JUSTIFY
                ),
                rtl_paragraph=True,
            )

        if level == 1:

            seen_level_1 = True

        # ----------------------------------------------------
        # Actual paragraph
        # ----------------------------------------------------

        paragraph = (
            anchor_paragraph
            .insert_paragraph_before()
        )

        _write_item_text(
            paragraph,
            item,
            size_pt=item.get("size_pt"),
        )

        # Native Word numbering only if the canvas did not already
        # write 1. / א. / 1) into the text (WYSIWYG).
        if apply_num:
            _set_num_pr(
                paragraph,
                ilvl=level - 1,
                num_id=num_id,
            )

        _style_paragraph(
            paragraph,
            size_pt=item.get("size_pt"),
            alignment=_alignment_for_item(item, WD_ALIGN_PARAGRAPH.JUSTIFY),
            rtl_paragraph=True,
            touch_runs=not item.get("runs"),
        )

        if apply_num:
            _apply_numbered_paragraph_indent(paragraph, level, doc)

    # Remove marker.
    parent = (
        anchor_paragraph._p.getparent()
    )

    if parent is not None:

        parent.remove(
            anchor_paragraph._p
        )



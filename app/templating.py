def extract_placeholders(
    docx_bytes: bytes,
) -> list[str]:
    """
    Return combined placeholders from:

    1. Jinja2 variables
    2. Native Word SDT Tags
    3. Native Word SDT Aliases
    """

    doc = DocxTemplate(
        io.BytesIO(docx_bytes)
    )

    jinja_vars = list(
        doc.get_undeclared_template_variables()
    )

    cc_tags = extract_content_controls(
        docx_bytes
    )

    extra = []
    if _docx_has_nemen_placeholder(docx_bytes) or _docx_has_distribution_heading(
        docx_bytes
    ):
        extra.append("Distribution")

    return sorted(
        list(
            set(
                jinja_vars
                + cc_tags
                + extra
            )
        )
    )


def _is_nemen_placeholder_text(text: str) -> bool:
    compact = _NEMEN_STRIP_RE.sub("", text or "")
    return compact == NEMEN_PLACEHOLDER.replace(" ", "")


def _docx_has_nemen_placeholder(docx_bytes: bytes) -> bool:
    try:
        from zipfile import ZipFile

        with ZipFile(io.BytesIO(docx_bytes)) as archive:
            for name in archive.namelist():
                if not name.endswith(".xml"):
                    continue
                if NEMEN_PLACEHOLDER in archive.read(name).decode(
                    "utf-8", errors="ignore"
                ):
                    return True
    except Exception:
        return False
    return False


def _docx_has_distribution_heading(docx_bytes: bytes) -> bool:
    try:
        from zipfile import ZipFile

        with ZipFile(io.BytesIO(docx_bytes)) as archive:
            for name in archive.namelist():
                if not name.endswith(".xml"):
                    continue
                if "רשימת תפוצה" in archive.read(name).decode(
                    "utf-8", errors="ignore"
                ):
                    return True
    except Exception:
        return False
    return False


def _nemen_placeholder_paragraphs(doc: Document) -> list:
    return [
        paragraph
        for paragraph in doc.paragraphs
        if _is_nemen_placeholder_text(paragraph.text)
    ]


def _replace_nemen_placeholders_with_distribution(
    doc: Document,
    names: list[str],
) -> None:
    """Keep the template looking like [נמען] / [נמען] / [נמען].
    The first dummy line supplies spacing/alignment; extras are removed;
    then any number of real names is inserted in that spot."""

    anchors = _nemen_placeholder_paragraphs(doc)
    if not anchors:
        return

    for extra in reversed(anchors[1:]):
        parent = extra._p.getparent()
        if parent is not None:
            parent.remove(extra._p)

    _insert_distribution_list_at_marker(
        doc,
        anchors[0],
        names,
    )



def _fill_scalar_sdt(
    doc: Document,
    sdt,
    value,
    field_name: str,
) -> None:

    if value is None:
        value = ""

    value = _normalize_hyphen_spacing(str(value))

    text_nodes = sdt.xpath(
        './/*[local-name()="t"]'
    )

    if text_nodes:

        text_nodes[0].text = value

        for node in text_nodes[1:]:

            node.text = ""

    else:

        # A genuinely empty content control (no runs at all yet) has
        # nothing for the block above to update - build a run/text pair
        # and attach it, otherwise the field silently stays blank.
        content_el = sdt.find(
            qn("w:sdtContent")
        )

        if content_el is not None:

            new_r = OxmlElement(
                "w:r"
            )

            new_t = OxmlElement(
                "w:t"
            )

            new_t.set(
                qn("xml:space"),
                "preserve",
            )

            new_t.text = value

            new_r.append(new_t)

            target_p = content_el.find(
                qn("w:p")
            )

            if target_p is not None:

                target_p.append(new_r)

            else:

                content_el.append(new_r)

    # Apply formatting to all runs inside SDT.
    for run_el in sdt.xpath(
        './/*[local-name()="r"]'
    ):

        from docx.text.run import Run

        run = Run(
            run_el,
            doc,
        )

        style = _current_style().field_style_overrides.get(
            field_name,
            {
                "size_pt": _current_style().body_size_pt,
                "bold": False,
                "italic": False,
                "underline": False,
            },
        )

        _style_run(
            run,
            size_pt=style.get(
                "size_pt",
                _current_style().body_size_pt,
            ),
            bold=style.get(
                "bold",
                False,
            ),
            italic=style.get(
                "italic",
                False,
            ),
            underline=style.get(
                "underline",
                False,
            ),
            rtl=True,
        )



def _get_current_dates() -> dict[str, str]:
    """
    Returns current Gregorian and Hebrew dates.

    Gregorian:
        14 אוגוסט 2026

    Hebrew date uses pyluach if installed.
    """

    today = datetime.now()

    hebrew_months = {
        1: "ינואר",
        2: "פברואר",
        3: "מרץ",
        4: "אפריל",
        5: "מאי",
        6: "יוני",
        7: "יולי",
        8: "אוגוסט",
        9: "ספטמבר",
        10: "אוקטובר",
        11: "נובמבר",
        12: "דצמבר",
    }

    rlm = "\u200f"

    gregorian_date = (
        f"{rlm}"
        f"{today.day:02d} "
        f"{hebrew_months[today.month]} "
        f"{today.year}"
    )

    try:
        from pyluach import dates

        heb_date = dates.HebrewDate.today()

        hebrew_date = (
            f"{rlm}"
            f"{heb_date.hebrew_date_string()}"
        )

    except ImportError:

        hebrew_date = (
            f'{rlm}'
            f'כ"ח אב תשפ"ו'
        )

    return {
        "Date_Army": gregorian_date,
        "Date_ArmyHebrew": hebrew_date,
    }


def _copy_hf_content(src, dest) -> None:
    if src is None or dest is None:
        return
    src_el = src._element
    dest_el = dest._element
    for child in list(dest_el):
        dest_el.remove(child)
    for child in src_el:
        dest_el.append(copy.deepcopy(child))


def _ensure_continuation_header_gap(doc: Document) -> None:
    """Keep one blank line under the running header on page 2+.

    Page 1 already has the letterhead in the body. Extra header height
    there would open a hole under סיווג / מספר עמוד. Different-first-page
    keeps the first-page header as-is and only pads the default header.
    """

    for section in doc.sections:
        if not section.different_first_page_header_footer:
            section.different_first_page_header_footer = True
            _copy_hf_content(section.header, section.first_page_header)
            _copy_hf_content(section.footer, section.first_page_footer)

        header = section.header
        paras = header.paragraphs
        if not (paras and not (paras[-1].text or "").strip()):
            paragraph = header.add_paragraph()
            _set_bidi(paragraph, rtl=True)
            pf = paragraph.paragraph_format
            pf.space_before = Pt(0)
            pf.space_after = Pt(0)
            pf.line_spacing = 1.5

        # python-docx may already have created an empty even header;
        # keep it in sync with the padded default so even pages 2+
        # still show סיווג / מספר עמוד and the blank line.
        _copy_hf_content(header, section.even_page_header)



# LLM / canvas often puts "1. " / "א. " / "1) " in the text as well as
# setting level. Word numbering already prints those markers, so a
# leftover prefix becomes "1. 1. רקע:". Strip one matching prefix.
_OUTLINE_PREFIX = {
    1: re.compile(r"^\s*\d+\.\s*"),
    2: re.compile(r"^\s*[\u05d0-\u05ea]\.\s*"),
    3: re.compile(r"^\s*\d+\)\s*"),
}


def _item_plain_text(item: dict) -> str:
    runs = item.get("runs") or []
    if runs:
        return "".join(str(run.get("text") or "") for run in runs)
    return str(item.get("text") or "")


def _text_has_outline_prefix(text: str) -> bool:
    raw = text or ""
    return bool(
        _OUTLINE_PREFIX[3].match(raw)
        or _OUTLINE_PREFIX[1].match(raw)
        or _OUTLINE_PREFIX[2].match(raw)
    )


def _should_apply_word_numbering(item: dict, level) -> bool:
    """Word numbering only when level is 1/2/3 AND the canvas text does
    not already contain 1. / א. / 1). Otherwise the document would
    duplicate markers or diverge from the canvas."""

    if level not in (1, 2, 3):
        return False
    return not _text_has_outline_prefix(_item_plain_text(item))


def _strip_duplicate_outline_markers(item: dict) -> dict:
    """Keep level; drop a leading 1. / א. / 1) from text and runs."""

    level = item.get("level")
    pattern = _OUTLINE_PREFIX.get(level)
    if pattern is None:
        return item

    text = str(item.get("text") or "")
    stripped = pattern.sub("", text, count=1)
    if stripped != text:
        item["text"] = stripped.strip()

    runs = item.get("runs")
    if not runs:
        return item

    joined = "".join(str(run.get("text") or "") for run in runs)
    match = pattern.match(joined)
    if not match:
        return item

    cut = match.end()
    kept: list[dict] = []
    skipped = 0
    for run in runs:
        piece = str(run.get("text") or "")
        if skipped >= cut:
            kept.append(run)
            continue
        end = skipped + len(piece)
        if end <= cut:
            skipped = end
            continue
        new_run = dict(run)
        new_run["text"] = piece[cut - skipped :]
        kept.append(new_run)
        skipped = cut

    item["runs"] = kept
    item["text"] = "".join(str(run.get("text") or "") for run in kept).strip()
    return item



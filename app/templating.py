def _set_bidi(
    paragraph,
    rtl: bool = True,
) -> None:

    p_pr = paragraph._p.get_or_add_pPr()

    existing = p_pr.find(
        qn("w:bidi")
    )

    if rtl:

        if existing is None:

            p_pr.append(
                OxmlElement("w:bidi")
            )

    else:

        if existing is not None:

            p_pr.remove(
                existing
            )



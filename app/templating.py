# Invisible bidi control / zero-width characters an LLM/source doc can
# leave in front of a line without it being visible in a screenshot -
# stripped before checking/displaying "אחריות" lines so they don't
# silently break the match. Built from codepoints (not pasted literally)
# so the characters stay unambiguous on review:
#   200B ZERO WIDTH SPACE      200E LEFT-TO-RIGHT MARK
#   200F RIGHT-TO-LEFT MARK    202A-202E bidi embedding/override controls
_BIDI_MARK_CODEPOINTS = [
    0x200B,
    0x200E,
    0x200F,
    0x202A,
    0x202B,
    0x202C,
    0x202D,
    0x202E,
]

_BIDI_MARKS_RE = re.compile(
    "[" + "".join(chr(cp) for cp in _BIDI_MARK_CODEPOINTS) + "]"
)

# An accidental leading numbering prefix (e.g. "ד. " or "3. "), in case
# the model glued one on despite being told not to number these lines.
_LEADING_NUMBERING_RE = re.compile(
    r"^(?:\d+[.)]|[א-ת][.)])\s*"
)


def _clean_achrayut_text(text: str) -> str:

    cleaned = _BIDI_MARKS_RE.sub("", text).strip()

    m = _LEADING_NUMBERING_RE.match(cleaned)

    if m:
        cleaned = cleaned[m.end():].strip()

    return cleaned


# Matches only a responsibility LABEL/HEADER line - "אחריות" followed by
# ":" (e.g. "אחריות: כלל המשתתפים"). A dash ("אחריות - X" / "אחריות-X")
# is deliberately NOT treated as a label anymore - only ":" counts.
# Deliberately does NOT match:
#   - "אחריות היא ערך חשוב בעבודה"   (starts with the word, but no ":"
#                                      right after - an ordinary
#                                      sentence, not a label)
#   - "האחריות צריכה להיות..."       ("ה" + "אחריות" as one word - not
#                                      even a prefix match)
# Always run text through _clean_achrayut_text() first so a stray bidi
# mark or numbering prefix in front of "אחריות" doesn't hide it from
# this pattern.
_ACHRAYUT_CLAUSE_RE = re.compile(
    r"^\s*אחריות\s*:"
)


def _is_achrayut_clause(cleaned_text: str) -> bool:

    return bool(
        _ACHRAYUT_CLAUSE_RE.match(cleaned_text)
    )


def _insert_structured_content_before_sdt(
    doc: Document,
    sdt,
    items: list[dict],
) -> None:
    """
    Replace a block-level Content SDT with actual Word paragraphs.

    The SDT itself is removed.

    Example input:

        [
            {"level": 1, "text": "רקע"},
            {"level": 2, "text": "כידוע..."},
            {"level": 2, "text": "לאחרונה..."},
            {"level": 3, "text": "נתון נוסף..."}
        ]

    Result:

        1. רקע
        א. כידוע...
        ב. לאחרונה...
        1) נתון נוסף...
    """

    if not items:

        parent = sdt.getparent()

        if parent is not None:

            parent.remove(
                sdt
            )

        return

    num_id = _ensure_multilevel_numbering(
        doc
    )

    # Tracks whether a level-1 section has already been emitted. The
    # blank separator must only appear BETWEEN two level-1 sections, not
    # right after a level-0 intro paragraph (which sits directly above
    # the first "1." with no gap).
    seen_level_1 = False

    for item in items:

        if not isinstance(
            item,
            dict,
        ):
            continue

        # ----------------------------------------------------
        # Heading item (e.g. distribution-list section title)
        # ----------------------------------------------------

        if item.get("type") == "heading":

            heading_text = str(item.get("text", "")).strip()

            if heading_text:

                for _ in range(2):

                    blank = (
                        _new_paragraph_before_sdt(
                            doc,
                            sdt,
                        )
                    )

                    _style_paragraph(
                        blank,
                        alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
                        rtl_paragraph=True,
                    )

                paragraph = (
                    _new_paragraph_before_sdt(
                        doc,
                        sdt,
                    )
                )

                _write_item_text(
                    paragraph,
                    {"text": heading_text, "runs": item.get("runs")},
                    size_pt=item.get("size_pt", 14),
                    bold=item.get("bold", True),
                    underline=item.get("underline", True),
                )

                _style_paragraph(
                    paragraph,
                    size_pt=item.get("size_pt", 14),
                    bold=item.get("bold", True),
                    underline=item.get("underline", True),
                    alignment=_alignment_for_item(item, WD_ALIGN_PARAGRAPH.JUSTIFY),
                    rtl_paragraph=True,
                    touch_runs=not item.get("runs"),
                )

            continue

        # ----------------------------------------------------
        # Table item (from an uploaded docx/msg file, or an
        # explicitly-built list like the distribution overflow table)
        # ----------------------------------------------------

        if item.get("type") == "table":

            rows = item.get("rows") or []

            if rows:

                _new_table_before_sdt(
                    sdt,
                    rows,
                    align=item.get("align", "center"),
                    header_row=item.get("header_row", True),
                    bold_cells=item.get("bold_cells", False),
                    equal_columns=item.get("equal_columns", False),
                    bidi=item.get("bidi", True),
                )

            continue

        level = item.get(
            "level"
        )

        if level not in (
            0,
            1,
            2,
            3,
        ):
            level = 0

        apply_num = _should_apply_word_numbering(item, level)
        if apply_num:
            item = _strip_duplicate_outline_markers(item)

        text = str(
            item.get(
                "text",
                "",
            )
        ).strip()

        if not text and not item.get("runs"):
            continue

        # ----------------------------------------------------
        # "אחריות" lines
        #
        # Responsibility/deadline annotations (e.g. "אחריות - כלל
        # המשתתפים") are not part of the numbered hierarchy - style
        # them per the current style's field_style_overrides["אחריות"]
        # (bold, underline, left-aligned) regardless of whatever level
        # was assigned, and skip numbering entirely.
        # ----------------------------------------------------

        achrayut_text = _clean_achrayut_text(text)

        if _is_achrayut_clause(achrayut_text):

            achrayut_style = _current_style().field_style_overrides.get(
                "אחריות",
                {},
            )

            blank = (
                _new_paragraph_before_sdt(
                    doc,
                    sdt,
                )
            )

            _style_paragraph(
                blank,
                alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
                rtl_paragraph=True,
            )

            paragraph = (
                _new_paragraph_before_sdt(
                    doc,
                    sdt,
                )
            )

            _add_direction_aware_runs(
                paragraph,
                achrayut_text,
            )

            _style_paragraph(
                paragraph,
                size_pt=achrayut_style.get(
                    "size_pt", _current_style().body_size_pt
                ),
                bold=achrayut_style.get(
                    "bold", True
                ),
                underline=achrayut_style.get(
                    "underline", True
                ),
                # Word mirrors w:jc for RTL/bidi paragraphs (same
                # mirroring already established for w:ind elsewhere in
                # this file) - RIGHT here is what actually displays as
                # left-aligned. Confirmed via Word's own alignment
                # button state, not just rendering appearance.
                alignment=achrayut_style.get(
                    "alignment", WD_ALIGN_PARAGRAPH.RIGHT
                ),
                rtl_paragraph=True,
            )

            continue

        # ----------------------------------------------------
        # Level 0
        #
        # Plain paragraph.
        # NO numbering.
        # ----------------------------------------------------

        if level == 0:

            paragraph = (
                _new_paragraph_before_sdt(
                    doc,
                    sdt,
                )
            )

            _write_item_text(
                paragraph,
                item,
                size_pt=item.get("size_pt"),
            )

            _style_paragraph(
                paragraph,
                size_pt=item.get("size_pt"),
                alignment=_alignment_for_item(item, WD_ALIGN_PARAGRAPH.JUSTIFY),
                rtl_paragraph=True,
                touch_runs=not item.get("runs"),
            )

            continue

        # ----------------------------------------------------
        # Level 1
        #
        # Add a small separation before each new main section,
        # but only once a previous level-1 section already exists.
        # ----------------------------------------------------

        if (
            level == 1
            and
            seen_level_1
        ):

            blank = (
                _new_paragraph_before_sdt(
                    doc,
                    sdt,
                )
            )

            _style_paragraph(
                blank,
                alignment=(
                    WD_ALIGN_PARAGRAPH.JUSTIFY
                ),
                rtl_paragraph=True,
            )

        if level == 1:

            seen_level_1 = True

        # ----------------------------------------------------
        # Create actual Word paragraph
        # ----------------------------------------------------

        paragraph = (
            _new_paragraph_before_sdt(
                doc,
                sdt,
            )
        )

        _write_item_text(
            paragraph,
            item,
            size_pt=item.get("size_pt"),
        )

        # ----------------------------------------------------
        # Native Word numbering
        #
        # level 1 -> ilvl 0
        # level 2 -> ilvl 1
        # level 3 -> ilvl 2
        # ----------------------------------------------------

        # Native Word numbering only if the canvas did not already
        # write 1. / א. / 1) into the text (WYSIWYG).
        if apply_num:
            _set_num_pr(
                paragraph,
                ilvl=level - 1,
                num_id=num_id,
            )

        _style_paragraph(
            paragraph,
            size_pt=item.get("size_pt"),
            alignment=_alignment_for_item(item, WD_ALIGN_PARAGRAPH.JUSTIFY),
            rtl_paragraph=True,
            touch_runs=not item.get("runs"),
        )

        if apply_num:
            _apply_numbered_paragraph_indent(paragraph, level, doc)

    # --------------------------------------------------------
    # Remove the original SDT.
    # --------------------------------------------------------

    parent = sdt.getparent()

    if parent is not None:

        parent.remove(
            sdt
        )


# ============================================================
# SDT FILLING
# ============================================================

def _fill_content_controls(
    doc: Document,
    context: dict,
) -> bool:
    """
    Fill native Word SDTs.

    Special handling:

        Content = list
            -> generate real Word numbered paragraphs

        Distribution = list of names
            -> vertical list of paragraphs

    Other fields:

        scalar
            -> fill the SDT text normally

    Returns True if a Distribution SDT was filled.
    """

    filled_distribution = False

    sdt_elements = list(
        _get_all_sdt_elements(doc)
    )

    for sdt in sdt_elements:

        tag, alias = _get_sdt_tag_and_alias(
            sdt
        )

        if tag == "Title" or alias == "Title":
            continue

        matched_key = _find_context_key(
            tag,
            alias,
            context,
        )

        if matched_key is None:
            continue

        value = context.get(
            matched_key
        )

        # ----------------------------------------------------
        # CONTENT SDT
        # ----------------------------------------------------

        if (
            matched_key.lower()
            == _current_field_map().content_field.lower()
        ):

            if isinstance(
                value,
                list,
            ):

                _insert_structured_content_before_sdt(
                    doc,
                    sdt,
                    value,
                )

            continue

        # ----------------------------------------------------
        # DISTRIBUTION SDT — vertical list of names, any length
        # ----------------------------------------------------

        if (
            matched_key.lower()
            == _current_field_map().distribution_field.lower()
        ):

            names = normalize_distribution_names(value)
            _insert_distribution_list_before_sdt(
                doc,
                sdt,
                names,
            )
            filled_distribution = True
            continue

        # ----------------------------------------------------
        # Regular scalar SDT
        # ----------------------------------------------------

        if value:

            _fill_scalar_sdt(
                doc,
                sdt,
                value,
                matched_key,
            )

    return filled_distribution


# ============================================================
# BLANK PARAGRAPH HELPERS
# ============================================================

def _is_blank_paragraph(
    paragraph,
) -> bool:

    if paragraph.text.strip():
        return False

    if paragraph._p.findall(
        f".//{W_NS}drawing"
    ):
        return False

    # A numbered paragraph is not considered blank.
    if paragraph._p.find(
        qn("w:pPr")
    ) is not None:

        p_pr = paragraph._p.find(
            qn("w:pPr")
        )

        if p_pr.find(
            qn("w:numPr")
        ) is not None:

            return False

    return True


def _apply_line_spacing_everywhere(
    doc: Document,
    *,
    line_spacing: float = 1.5,
) -> None:
    """
    Set 1.5 line spacing on every paragraph in the final document -
    including the static template paragraphs (letterhead, distribution,
    signature block, ...), not just the ones the Content-insertion code
    builds.

    IMPORTANT:
    Only w:line is touched here. Paragraph spacing (space before/after)
    is left exactly as-is - the only place that should ever add extra
    space between paragraphs is the blank separator before each new
    level-1 section (see _insert_structured_content_before_sdt /
    _insert_structured_content_at_marker).
    """

    def _apply_to(paragraphs):

        for paragraph in paragraphs:

            paragraph.paragraph_format.line_spacing = (
                line_spacing
            )

    _apply_to(
        doc.paragraphs
    )

    for table in doc.tables:

        for row in table.rows:

            for cell in row.cells:

                _apply_to(
                    cell.paragraphs
                )


def _collapse_blank_paragraphs(
    doc: Document,
    max_consecutive: int = 1,
) -> None:

    run = []

    for paragraph in doc.paragraphs:

        if _is_blank_paragraph(
            paragraph
        ):

            run.append(
                paragraph
            )

        else:

            for extra in run[
                max_consecutive:
            ]:

                parent = (
                    extra._p.getparent()
                )

                if parent is not None:

                    parent.remove(
                        extra._p
                    )

            run = []

    for extra in run[
        max_consecutive:
    ]:

        parent = (
            extra._p.getparent()
        )

        if parent is not None:

            parent.remove(
                extra._p
            )



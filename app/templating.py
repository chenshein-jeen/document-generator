def _new_paragraph_before_sdt(
    doc: Document,
    sdt,
):
    """
    Create a new python-docx Paragraph and move its XML
    immediately before the SDT.

    This allows a block-level SDT to be replaced by real
    Word paragraphs while preserving its position.
    """

    paragraph_xml = OxmlElement(
        "w:p"
    )

    parent = sdt.getparent()

    index = parent.index(
        sdt
    )

    parent.insert(
        index,
        paragraph_xml,
    )

    return Paragraph(
        paragraph_xml,
        doc,
    )


def _distribution_field_style() -> dict:
    return _current_style().field_style_overrides.get("Distribution", {})


def _style_distribution_name_paragraph(paragraph, name) -> None:
    style = _distribution_field_style()
    item = _distribution_item_as_dict(name)
    if item is None:
        item = {"text": str(name)}
    rich = _write_item_text(
        paragraph,
        item,
        size_pt=style.get("size_pt"),
        bold=style.get("bold", False),
        italic=style.get("italic", False),
        underline=style.get("underline", False),
    )
    _style_paragraph(
        paragraph,
        size_pt=style.get("size_pt"),
        bold=style.get("bold", False),
        italic=style.get("italic", False),
        underline=style.get("underline", False),
        alignment=_alignment_for_item(
            item,
            style.get("alignment", WD_ALIGN_PARAGRAPH.CENTER),
        ),
        rtl_paragraph=True,
        space_after=style.get("space_after", Pt(24)),
        touch_runs=not rich,
    )


def _clone_paragraph_properties(source_p_el, target_p_el) -> None:
    source_ppr = source_p_el.find(qn("w:pPr"))
    if source_ppr is None:
        return
    existing = target_p_el.find(qn("w:pPr"))
    if existing is not None:
        target_p_el.remove(existing)
    target_p_el.insert(0, copy.deepcopy(source_ppr))


def _insert_distribution_list_at_marker(
    doc: Document,
    anchor_paragraph,
    names: list[str],
) -> None:
    """Replace a {{Distribution}} marker paragraph with one centered
    paragraph per recipient. Empty list removes the marker."""

    parent = anchor_paragraph._p.getparent()
    if parent is None:
        return

    index = parent.index(anchor_paragraph._p)

    for offset, name in enumerate(names):
        paragraph_xml = OxmlElement("w:p")
        _clone_paragraph_properties(anchor_paragraph._p, paragraph_xml)
        parent.insert(index + offset, paragraph_xml)
        paragraph = Paragraph(paragraph_xml, doc)
        _style_distribution_name_paragraph(paragraph, name)

    parent.remove(anchor_paragraph._p)


def _insert_distribution_list_after_heading(
    doc: Document,
    names: list[str],
) -> bool:
    """Insert one centered name line after the static רשימת תפוצה heading.
    The heading stays in the template; dummy [נמען] lines are not needed."""

    if not names:
        return False

    heading = next(
        (
            paragraph
            for paragraph in doc.paragraphs
            if paragraph.text.strip() == DISTRIBUTION_HEADING_TEXT
        ),
        None,
    )
    if heading is None:
        return False

    parent = heading._p.getparent()
    if parent is None:
        return False

    index = parent.index(heading._p) + 1
    for offset, name in enumerate(names):
        paragraph_xml = OxmlElement("w:p")
        parent.insert(index + offset, paragraph_xml)
        paragraph = Paragraph(paragraph_xml, doc)
        _style_distribution_name_paragraph(paragraph, name)

    return True


def _insert_distribution_list_before_sdt(
    doc: Document,
    sdt,
    names: list[str],
) -> None:
    """Replace a Distribution content control with one centered
    paragraph per recipient."""

    for name in names:
        paragraph = _new_paragraph_before_sdt(doc, sdt)
        _style_distribution_name_paragraph(paragraph, name)

    parent = sdt.getparent()
    if parent is not None:
        parent.remove(sdt)



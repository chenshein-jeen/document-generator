def _distribution_item_as_dict(value) -> dict | None:
    """Normalize one recipient to a dict the paragraph writer can use."""

    if value is None:
        return None
    if hasattr(value, "model_dump"):
        value = value.model_dump(by_alias=True)
    if isinstance(value, dict):
        runs = value.get("runs") or []
        dumped_runs = []
        for run in runs:
            if hasattr(run, "model_dump"):
                dumped_runs.append(run.model_dump(by_alias=True))
            elif isinstance(run, dict):
                dumped_runs.append(run)
        item = dict(value)
        if dumped_runs:
            item["runs"] = dumped_runs
        text = str(item.get("text") or "").strip()
        if text or dumped_runs:
            if dumped_runs and not text:
                item["text"] = "".join(
                    str(run.get("text") or "") for run in dumped_runs
                )
            return item
        return None
    return None


def normalize_distribution_names(value) -> list:
    """Turn a Distribution value into a flat list of recipient names.

    Accepts a JSON array, a comma-separated string, or newline-separated
    text. Entries may be strings or {text, runs} objects (bold/underline).
    Nested lists are flattened. Empty tokens are dropped.
    """

    if value is None:
        return []

    as_item = _distribution_item_as_dict(value)
    if as_item is not None:
        return [as_item]

    if isinstance(value, (list, tuple)):
        names: list = []
        for item in value:
            names.extend(normalize_distribution_names(item))
        return names

    if not isinstance(value, str):
        value = str(value)

    return [part.strip() for part in re.split(r"[\n,]+", value) if part.strip()]


def fold_distribution_fields(
    context: dict,
    distribution_field: str = "Distribution",
    placeholders: list[str] | None = None,
) -> str:
    """Merge Distribution + Distribution_2..N into one list on the
    canonical placeholder key. Returns that key. Indexed leftover keys
    are removed from context."""

    indexed: dict[int, list[str]] = {}
    extra_keys: list[str] = []
    canonical_key = distribution_field

    if placeholders:
        matched = next(
            (p for p in placeholders if p.lower() == distribution_field.lower()),
            None,
        )
        if matched:
            canonical_key = matched

    for key, value in list(context.items()):
        match = _DISTRIBUTION_INDEXED_RE.fullmatch(key)
        if not match:
            continue
        suffix = match.group(1)
        index = 1 if suffix is None else int(suffix)
        if suffix is None and not placeholders:
            canonical_key = key
        indexed.setdefault(index, []).extend(normalize_distribution_names(value))
        extra_keys.append(key)

    names: list[str] = []
    for index in sorted(indexed):
        names.extend(indexed[index])

    for key in extra_keys:
        context.pop(key, None)

    if names or extra_keys:
        context[canonical_key] = names

    return canonical_key



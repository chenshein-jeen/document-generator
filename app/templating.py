def _max_run_size_pt(
    paragraph,
) -> float:

    sizes = [
        r.font.size.pt
        for r in paragraph.runs
        if r.font.size is not None
    ]

    return (
        max(sizes)
        if sizes
        else 0
    )


def _apply_static_field_styles_post_render(
    doc: Document,
    render_context: dict,
) -> None:

    for field, style in _current_style().field_style_overrides.items():

        value = render_context.get(
            field
        )

        if not value:
            continue

        if not isinstance(
            value,
            str,
        ):
            continue

        for paragraph in doc.paragraphs:

            if value not in paragraph.text:
                continue

            max_size = _max_run_size_pt(
                paragraph
            )

            if (
                max_size
                and
                max_size
                < HIDDEN_TEXT_THRESHOLD_PT
            ):
                continue

            _style_paragraph(
                paragraph,
                **style,
            )

            for run in paragraph.runs:

                _style_run(
                    run,
                    size_pt=style.get(
                        "size_pt",
                        _current_style().body_size_pt,
                    ),
                    bold=style.get(
                        "bold",
                        False,
                    ),
                    italic=style.get(
                        "italic",
                        False,
                    ),
                    underline=style.get(
                        "underline",
                        False,
                    ),
                    rtl=True,
                )


